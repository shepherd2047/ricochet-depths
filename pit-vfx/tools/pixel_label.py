"""Writes a text label as a PPM in a 5x7 pixel font (no PIL needed): pixel_label.py TEXT out.ppm [scale] [rrggbb]"""
import sys
F = {
 'A': "01110 10001 10001 11111 10001 10001 10001", 'B': "11110 10001 10001 11110 10001 10001 11110",
 'E': "11111 10000 10000 11110 10000 10000 11111", 'K': "10001 10010 10100 11000 10100 10010 10001",
 'M': "10001 11011 10101 10101 10001 10001 10001", 'P': "11110 10001 10001 11110 10000 10000 10000",
 'R': "11110 10001 10001 11110 10100 10010 10001", 'I': "01110 00100 00100 00100 00100 00100 01110",
 'S': "01111 10000 10000 01110 00001 00001 11110", 'Y': "10001 10001 01010 00100 00100 00100 00100",
 'L': "10000 10000 10000 10000 10000 10000 11111", 'T': "11111 00100 00100 00100 00100 00100 00100",
 'G': "01111 10000 10000 10111 10001 10001 01111", 'H': "10001 10001 10001 11111 10001 10001 10001",
 'N': "10001 11001 10101 10011 10001 10001 10001", 'O': "01110 10001 10001 10001 10001 10001 01110",
 'C': "01111 10000 10000 10000 10000 10000 01111", 'X': "10001 10001 01010 00100 01010 10001 10001",
 'W': "10001 10001 10001 10101 10101 10101 01010", 'D': "11110 10001 10001 10001 10001 10001 11110",
 'U': "10001 10001 10001 10001 10001 10001 01110", 'F': "11111 10000 10000 11110 10000 10000 10000",
 'Z': "11111 00001 00010 00100 01000 10000 11111", 'V': "10001 10001 10001 10001 10001 01010 00100",
 ' ': "00000 00000 00000 00000 00000 00000 00000", '-': "00000 00000 00000 11111 00000 00000 00000",
 '/': "00001 00010 00010 00100 01000 01000 10000",
}
text, out = sys.argv[1].upper(), sys.argv[2]
s = int(sys.argv[3]) if len(sys.argv) > 3 else 4
c = bytes.fromhex(sys.argv[4]) if len(sys.argv) > 4 else b'\xff\xff\xff'
bg = bytes.fromhex('262937')
pad = 2
W, H = (len(text) * 6 - 1 + pad * 2) * s, (7 + pad * 2) * s
px = bytearray(bg * (W * H))
for i, ch in enumerate(text):
    rows = F[ch].split()
    for y in range(7):
        for x in range(5):
            if rows[y][x] == '1':
                for yy in range(s):
                    for xx in range(s):
                        X, Y = (pad + i * 6 + x) * s + xx, (pad + y) * s + yy
                        px[(Y * W + X) * 3:(Y * W + X) * 3 + 3] = c
open(out, 'wb').write(b'P6 %d %d 255\n' % (W, H) + px)
