"""Write ../LAYOUT-TABLES.md: every UI element of every screen, in art px (180x320, top-left origin)."""
import layout as L
import sprites as SP

SKIP = ('scene/', 'safe/', 'mock/')

def size(e, S):
    if 'w' in e: return e['w'], e['h']
    if e['k'] == 'img':
        h, w = S[e['spr']].shape[:2]; return w * e['s'], h * e['s']
    return '', ''

def kind(e):
    return {'n9': 'Image (Sliced)', 'img': 'Image (Simple)', 'tile': 'Image (Tiled)', 'num': 'PixelNumber',
            'txt': 'TMP Text', 'rect': 'Image (white, tinted)', 'ell': 'Image'}[e['k']]

def detail(e):
    k = e['k']
    if k in ('n9', 'img', 'tile'): return f"`{e['spr']}`" + (f" ×{e['s']}" if e.get('s', 1) != 1 else '')
    if k == 'num': return f"font `{e['font']}`, \"{e['txt']}\", align {e['anchor']}" + (f", ×{e['s']}" if e['s'] != 1 else '') + (f", tint #{e['tint']}" if e['tint'] else '')
    if k == 'txt': return f"\"{e['txt']}\" · {e['pt']}pt {e['wt']} #{e['col']} · {e['ha'].lower()}/{e['va'].lower()}" + ('' if e['shadow'] else ' · no shadow')
    if k == 'rect': return f"#{e['col']} @ {e['op']:.2f}"
    return ''

S = SP.all_sprites()
out = ['# Layout tables', '',
       'Generated by `tools/dump_layout.py` from `tools/layout.py`; do not edit by hand.', '',
       'Units: art px on the 180×320 design grid, origin top-left, y down. `num` x/y is the anchor point of the string '
       '(l = left edge, c = centre, r = right edge; y = top of glyphs). Text sizes are Figma pt at ×2 preview; '
       'divide by 2 for art px (see UI-SPEC §6). Placeholder scene layers are omitted.', '']
for name, fn in L.SCREENS:
    out += [f'## {name}', '', '| element | type | x | y | w | h | sprite / content |', '|---|---|---:|---:|---:|---:|---|']
    for e in fn():
        if e['name'].startswith(SKIP): continue
        w, h = size(e, S)
        out.append(f"| `{e['name']}` | {kind(e)} | {e['x']} | {e['y']} | {w} | {h} | {detail(e)} |")
    out.append('')
open('../LAYOUT-TABLES.md', 'w').write('\n'.join(out))
print(len(out), 'lines')
